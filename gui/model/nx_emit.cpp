std::string sanitize(const std::string &s) {
    std::string o;
    for (unsigned char c : s) {
        if (std::isalnum(c) || c == '_') o += (char)c;
        else o += '_';
    }
    if (o.empty()) o = "sub";
    if (std::isdigit((unsigned char)o[0])) o = "sub_" + o;
    return o;
}

std::string addr_id(uint64_t addr) {
    std::ostringstream os;
    os << "sub_" << std::hex << addr;
    return os.str();
}

std::string hex_addr(uint64_t addr) {
    std::ostringstream os;
    os << "0x" << std::hex << addr;
    return os.str();
}

uint64_t file_offset(const macho_binary_t &bin, uint64_t addr, size_t len) {
    for (int i = 0; i < bin.nsections; i++) {
        const macho_section_t &s = bin.sections[i];
        if (addr < s.vaddr || addr + len > s.vaddr + s.size) continue;
        return s.file_offset + (addr - s.vaddr);
    }
    return (uint64_t)-1;
}

bool read_bytes(const macho_binary_t &bin, uint64_t addr, size_t len,
                std::vector<uint8_t> &out) {
    uint64_t off = file_offset(bin, addr, len);
    if (off == (uint64_t)-1 || off + len > bin.size) return false;
    out.assign(bin.data + off, bin.data + off + len);
    return true;
}

const char *arch_name(macho_arch_t a) {
    switch (a) {
        case MACHO_ARCH_X86_64: return "x86_64";
        case MACHO_ARCH_ARM64: return "arm64";
        case MACHO_ARCH_RISCV64: return "riscv64";
        case MACHO_ARCH_X86_32: return "x86";
        default: return "unknown";
    }
}

std::vector<size_t> function_order(const macho_binary_t &bin) {
    std::vector<size_t> v;
    for (int i = 0; i < bin.nfunctions; i++) v.push_back((size_t)i);
    std::sort(v.begin(), v.end(), [&](size_t a, size_t b) {
        return bin.functions[a].start < bin.functions[b].start;
    });
    return v;
}

std::string function_label(const macho_binary_t &bin, const Graph &g, size_t i) {
    const auto &f = bin.functions[i];
    const auto &fs = g.functions();
    std::ostringstream os;
    os << (f.name[0] ? f.name : addr_id(f.start));
    if (i < fs.size()) {
        if (fs[i]->role >= 0) os << " role=" << fs[i]->role;
        if (fs[i]->annulus >= 0) os << " annulus=" << fs[i]->annulus;
    }
    os << " size=" << (f.end > f.start ? f.end - f.start : 0);
    return os.str();
}

std::vector<std::pair<size_t, size_t>> call_edges(const macho_binary_t &bin) {
    std::vector<std::pair<size_t, size_t>> out;
    std::set<std::pair<size_t, size_t>> seen;
    auto index_of = [&](uint64_t addr) -> int {
        for (int i = 0; i < bin.nfunctions; i++) {
            if (addr >= bin.functions[i].start && addr < bin.functions[i].end) return i;
        }
        return -1;
    };
    for (int i = 0; i < bin.ncall_chains; i++) {
        const auto &c = bin.call_chains[i];
        int a = index_of(c.caller);
        int b = index_of(c.callee);
        if (a < 0 || b < 0 || a == b) continue;
        if (seen.insert({(size_t)a, (size_t)b}).second) out.push_back({(size_t)a, (size_t)b});
    }
    for (int i = 0; i < bin.nxrefs; i++) {
        const auto &x = bin.xrefs[i];
        if (!x.is_call && x.type != MACHO_XREF_TYPE_CALL) continue;
        int a = index_of(x.from);
        int b = index_of(x.to ? x.to : x.resolved_target);
        if (a < 0 || b < 0 || a == b) continue;
        if (seen.insert({(size_t)a, (size_t)b}).second) out.push_back({(size_t)a, (size_t)b});
    }
    return out;
}

void emit_hex_line(std::ostream &os, uint64_t addr, const std::vector<uint8_t> &b,
                   size_t begin, size_t n) {
    os << std::hex << std::setw(16) << std::setfill('0') << addr + begin << "  ";
    os << std::dec << std::setfill(' ');
    for (size_t i = 0; i < 16; i++) {
        if (i < n) {
            os << std::hex << std::setw(2) << std::setfill('0') << (unsigned)b[begin + i]
               << std::dec << std::setfill(' ') << ' ';
        } else {
            os << "   ";
        }
        if (i == 7) os << ' ';
    }
    os << " |";
    for (size_t i = 0; i < n; i++) {
        unsigned char c = b[begin + i];
        os << (c >= 32 && c < 127 ? (char)c : '.');
    }
    os << "|\n";
}

