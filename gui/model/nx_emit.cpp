bool write_cpp(const macho_binary_t &bin, const Graph &g, const std::string &path,
               const EmitOptions &opt, std::string *err) {
    std::ofstream f(path, std::ios::binary);
    if (!f) { if (err) *err = "cannot write: " + path; return false; }

    f << "// generated by neodax-viewer static analysis\n";
    f << "// file: " << bin.filepath << "\n";
    f << "// arch: " << arch_name(bin.arch) << " entry: " << hex_addr(bin.entry)
      << " image: " << hex_addr(bin.base) << "+" << hex_addr(bin.image_size) << "\n";
    f << "// ===== NX TEMPLATE =====\n";
    f << "// id: static." << std::hex << bin.base << std::dec << "\n";
    f << "// kind: code\n";
    f << "// target: " << bin.filepath << "\n";
    for (size_t i : function_order(bin))
        f << "// node: " << addr_id(bin.functions[i].start) << " "
          << function_label(bin, g, i)
          << " element:" << addr_id(bin.functions[i].start) << " action:code\n";
    for (auto &e : call_edges(bin))
        f << "// link: " << addr_id(bin.functions[e.first].start) << " calls "
          << addr_id(bin.functions[e.second].start) << "\n";
    f << "// ===== /NX TEMPLATE =====\n\n";
    f << "#include <cstdint>\n\n";
    f << "namespace nx_re {\n\n";
    f << "struct image_info {\n";
    f << "    static constexpr const char *file = \"" << bin.filepath << "\";\n";
    f << "    static constexpr const char *arch = \"" << arch_name(bin.arch) << "\";\n";
    f << "    static constexpr std::uint64_t entry = " << hex_addr(bin.entry) << ";\n";
    f << "};\n\n";

    size_t count = 0;
    for (size_t i : function_order(bin)) {
        if (opt.max_functions && count++ >= opt.max_functions) break;
        const auto &fn = bin.functions[i];
        std::string id = addr_id(fn.start);
        std::string label = function_label(bin, g, i);
        f << "// " << label << "\n";
        f << "// " << hex_addr(fn.start) << " .. " << hex_addr(fn.end) << "\n";
        f << "void " << id << "() {\n";

        if (opt.include_bytes && fn.end > fn.start) {
            std::vector<uint8_t> bytes;
            if (read_bytes(bin, fn.start, (size_t)(fn.end - fn.start), bytes)) {
                f << "    static const std::uint8_t code[] = {";
                for (size_t k = 0; k < bytes.size(); k++) {
                    if (k % 16 == 0) f << "\n        ";
                    f << "0x" << std::hex << std::setw(2) << std::setfill('0')
                      << (unsigned)bytes[k] << std::dec << std::setfill(' ')
                      << (k + 1 < bytes.size() ? "," : "") << " ";
                }
                f << "\n    };\n";
                f << "    (void)code;\n";
            }
        }

        if (opt.include_instructions && bin.ninsns > 0 && bin.insns) {
            const macho_insn_t *begin = bin.insns;
            const macho_insn_t *end = bin.insns + bin.ninsns;
            const macho_insn_t *p = std::lower_bound(begin, end, fn.start,
                [](const macho_insn_t &x, uint64_t a) { return x.address < a; });
            for (; p != end && p->address < fn.end; p++) {
                if (p->address < fn.start) continue;
                f << "    // " << hex_addr(p->address) << ": " << p->mnemonic;
                if (p->operands[0]) f << " " << p->operands;
                f << "\n";
            }
        }
        f << "}\n\n";
    }
    f << "} // namespace nx_re\n";
    return true;
}

bool write_hex(const macho_binary_t &bin, const std::string &path,
               const EmitOptions &opt, std::string *err) {
    std::ofstream f(path, std::ios::binary);
    if (!f) { if (err) *err = "cannot write: " + path; return false; }

    f << "# file: " << bin.filepath << "\n";
    f << "# arch: " << arch_name(bin.arch) << " entry: " << hex_addr(bin.entry) << "\n";
    size_t count = 0;
    for (size_t i : function_order(bin)) {
        if (opt.max_functions && count++ >= opt.max_functions) break;
        const auto &fn = bin.functions[i];
        f << "\n# function " << hex_addr(fn.start) << " "
          << (fn.name[0] ? fn.name : addr_id(fn.start)) << " size="
          << (fn.end > fn.start ? fn.end - fn.start : 0) << "\n";
        if (fn.end <= fn.start) continue;
        std::vector<uint8_t> bytes;
        if (!read_bytes(bin, fn.start, (size_t)(fn.end - fn.start), bytes)) continue;
        for (size_t k = 0; k < bytes.size(); k += 16)
            emit_hex_line(f, fn.start, bytes, k, std::min<size_t>(16, bytes.size() - k));
    }
    return true;
}

bool write_nodes(const macho_binary_t &bin, const Graph &g, const std::string &path,
                 const EmitOptions &opt, std::string *err) {
    std::ofstream f(path, std::ios::binary);
    if (!f) { if (err) *err = "cannot write: " + path; return false; }
    f << "# generated by neodax-viewer static analysis\n";
    size_t count = 0;
    for (size_t i : function_order(bin)) {
        if (opt.max_functions && count++ >= opt.max_functions) break;
        f << "node " << addr_id(bin.functions[i].start) << " "
          << function_label(bin, g, i)
          << " element:" << addr_id(bin.functions[i].start) << " action:code\n";
    }
    for (auto &e : call_edges(bin))
        f << "link " << addr_id(bin.functions[e.first].start) << " calls "
          << addr_id(bin.functions[e.second].start) << "\n";
    return true;
}

